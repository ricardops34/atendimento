import { Test, TestingModule } from '@nestjs/testing';
import { UnauthorizedException } from '@nestjs/common';
import { JwtService } from '@nestjs/jwt';
import * as bcrypt from 'bcrypt';
import { AuthService } from './auth.service';
import { PrismaService } from '../prisma/prisma.service';

describe('AuthService', () => {
  let service: AuthService;
  let prisma: { user: { findFirst: jest.Mock } };

  beforeEach(async () => {
    prisma = {
      user: {
        findFirst: jest.fn(),
      },
    };

    const module: TestingModule = await Test.createTestingModule({
      providers: [
        AuthService,
        { provide: PrismaService, useValue: prisma },
        { provide: JwtService, useValue: { sign: jest.fn().mockReturnValue('token') } },
      ],
    }).compile();

    service = module.get(AuthService);
  });

  it('accepts bcrypt password generated by seed', async () => {
    prisma.user.findFirst.mockResolvedValue({
      id: 1,
      email: 'admin@fallback.com',
      password: await bcrypt.hash('admin123', 4),
      isActive: true,
      profileId: 1,
      profile: { id: 1, name: 'Administrador', menu: { isActive: true, items: [] } },
      userEmpresas: [
        {
          empresaId: 1,
          empresa: { id: 1, name: 'Default Empresa' },
        },
      ],
    });

    await expect(
      service.validateUser({ email: 'admin@fallback.com', password: 'admin123' }),
    ).resolves.toMatchObject({ email: 'admin@fallback.com' });
  });

  it('rejects invalid password', async () => {
    prisma.user.findFirst.mockResolvedValue({
      id: 1,
      email: 'admin@fallback.com',
      password: await bcrypt.hash('admin123', 4),
      isActive: true,
      profileId: 1,
      profile: { id: 1, name: 'Administrador', menu: { isActive: true, items: [] } },
      userEmpresas: [
        {
          empresaId: 1,
          empresa: { id: 1, name: 'Default Empresa' },
        },
      ],
    });

    await expect(
      service.validateUser({ email: 'admin@fallback.com', password: 'errada' }),
    ).rejects.toBeInstanceOf(UnauthorizedException);
  });

  it('requires empresa selection when user has access to multiple empresas', async () => {
    const result = await service.login({
      id: 1,
      email: 'admin@fallback.com',
      name: 'Admin',
      profileId: 1,
      profile: { id: 1, name: 'Administrador', menu: { isActive: true, items: [] } },
      userEmpresas: [
        {
          empresaId: 1,
          empresa: { id: 1, name: 'Default Empresa' },
          isDefault: true,
        },
        {
          empresaId: 2,
          empresa: { id: 2, name: 'Filial 2' },
          isDefault: false,
        },
      ],
    } as any);

    expect(result).toEqual({
      requiresEmpresaSelection: true,
      empresaOptions: [
        { empresaId: 1, empresaName: 'Default Empresa', isDefault: true },
        { empresaId: 2, empresaName: 'Filial 2', isDefault: false },
      ],
    });
  });

  it('returns menu tree based on registered menus for selected empresa', async () => {
    const result = await service.login({
      id: 1,
      email: 'admin@fallback.com',
      name: 'Admin',
      profileId: 1,
      profile: {
        id: 1,
        name: 'Administrador',
        menu: {
          isActive: true,
          items: [{
            sortOrder: 10,
            isActive: true,
            routine: {
              name: 'Usuarios',
              shortLabel: 'USR',
              icon: 'an an-users-three',
              path: '/configuracoes/usuarios',
              isActive: true,
              moduleId: 5,
              module: { id: 5, key: 'configuracoes', name: 'Configuracoes' },
            },
          }],
        },
      },
      userEmpresas: [
        {
          empresaId: 1,
          empresa: { id: 1, name: 'Default Empresa' },
          isDefault: true,
        },
      ],
    } as any, 1);

    expect(result?.user?.menus).toEqual([
      {
        label: 'Configuracoes',
        shortLabel: 'CON',
        icon: 'an an-users-three',
        subItems: [
          {
            label: 'Usuarios',
            shortLabel: 'USR',
            icon: 'an an-users-three',
            link: '/configuracoes/usuarios',
          },
        ],
      },
    ]);
    expect(result?.user?.availableEmpresas).toEqual([
      { empresaId: 1, empresaName: 'Default Empresa', isDefault: true },
    ]);
    expect(result?.user?.profile).toBe('Administrador');
    expect(result?.user?.profileId).toBe(1);
  });

  it('orders menu groups by module order before module name', async () => {
    const menuItem = (module: any, routineName: string) => ({
      sortOrder: 10,
      isActive: true,
      routine: {
        name: routineName,
        shortLabel: routineName.substring(0, 3).toUpperCase(),
        icon: 'an an-folder',
        path: `/${routineName.toLowerCase()}`,
        isActive: true,
        moduleId: module.id,
        module,
      },
    });
    const result = await service.login({
      id: 1,
      email: 'admin@fallback.com',
      name: 'Admin',
      profileId: 1,
      profile: {
        id: 1,
        name: 'Administrador',
        menu: {
          isActive: true,
          items: [
            menuItem({ id: 1, key: 'basicos', name: 'Básicos', sortOrder: 20 }, 'Estados'),
            menuItem({ id: 2, key: 'usuarios', name: 'Usuário', sortOrder: 10 }, 'Perfis'),
          ],
        },
      },
      userEmpresas: [{
        empresaId: 1,
        empresa: { id: 1, name: 'Default Empresa' },
        isDefault: true,
      }],
    } as any, 1);

    expect(result?.user?.menus.map((menu) => menu.label)).toEqual(['Usuário', 'Básicos']);
  });
});
